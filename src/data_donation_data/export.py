"""
Export configuration management (``ddd_export.yaml``).

YAML structure
--------------

.. code-block:: yaml

    # Optional: human-readable names for task / assignment IDs.
    tasks:
      "862": YouTube Watch History
    assignments:
      "359": What IF - Spanish

    # Per-source, per-table field settings.
    # Each field value is one of:
    #   true          — include the field as-is
    #   false         — exclude the field from exports
    #   "alias_name"  — include and rename to alias_name
    #
    # Fields not mentioned are included as-is (same as true).

    facebook:
      Ads Interests:
        topics_v2.topics_v2: true
        junk_col: false
      Comments:
        comment: true
        dutch_comment: comment    # alias -> 'comment'

Running ``init_export_yaml`` is always safe: it adds newly discovered
fields while leaving all existing settings untouched.
"""

from __future__ import annotations

import re
import sqlite3
import unicodedata
from pathlib import Path
from typing import Any

import yaml

#: Default path for the export configuration file.
DEFAULT_YAML_PATH = Path("ddd_export.yaml")

#: Top-level YAML keys that are not source names.
_RESERVED_KEYS: frozenset[str] = frozenset({"tasks", "assignments"})

_YAML_HEADER = """\
# ddd_export.yaml — export configuration
# Generated by `ddd create-config`. Edit freely; re-run to pick up new fields.
#
# tasks / assignments (optional)
#   Map task or assignment IDs to human-readable names.
#
# Per-source configuration.  Each table block starts with an optional:
#   .alias: canonical_table_name   — rename/merge this table in exports
#
# Per-field settings (remaining keys in a table block):
#   field_name: alias_name    — include, renamed to alias_name
#   field_name: true          — include as-is (original name)
#   field_name: false         — exclude from exports
#
# Fields not mentioned are included as-is.
# New fields added by `ddd create-config` get an auto-generated alias
# (last dot-segment, lowercased, spaces→underscores, ASCII-only).
#
# Example:
#   facebook:
#     Likes And Reactions:
#       .alias: likes_and_reactions
#       timestamp: timestamp
#       ent_name: ent_name
#     Likes And Reactions 1:
#       .alias: likes_and_reactions   # merge with the table above
#       timestamp: timestamp

"""

#: Output columns produced by :func:`export_data`.
EXPORT_COLUMNS: list[str] = [
    "source",
    "table",
    "participant",
    "assignment",
    "task",
    "field",  # canonical / aliased name
    "original_field",  # raw DB field name
    "row_index",
    "value",
]


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _normalize_alias(name: str) -> str:
    """
    Convert *name* to a clean snake_case ASCII identifier.

    Steps: NFKD-decompose → drop non-ASCII → lowercase →
    replace runs of non-alphanumeric chars with ``_`` →
    strip leading/trailing ``_``.
    """
    nfkd = unicodedata.normalize("NFKD", name)
    ascii_str = nfkd.encode("ascii", "ignore").decode("ascii")
    lower = ascii_str.lower()
    slug = re.sub(r"[^a-z0-9]+", "_", lower)
    return slug.strip("_") or "field"


def _auto_field_alias(field: str) -> str:
    """Auto-alias for a field: normalize the last dot-separated segment."""
    return _normalize_alias(field.rsplit(".", 1)[-1])


def _auto_table_alias(table_name: str) -> str:
    """Auto-alias for a table: normalize the full table name."""
    return _normalize_alias(table_name)


def _parse_table_config(raw: Any) -> dict[str, bool | str]:
    """
    Parse a raw table block into ``{field: true/false/"alias"}``.

    Accepts both the new simple format and old legacy formats gracefully.
    """
    if not isinstance(raw, dict):
        return {}
    result: dict[str, bool | str] = {}
    for field, setting in raw.items():
        if isinstance(setting, bool):
            result[str(field)] = setting
        elif isinstance(setting, str):
            result[str(field)] = setting  # alias
        elif isinstance(setting, list):
            # Old canonical-group format: treat as alias to the key name itself
            result[str(field)] = True
        # ignore other types
    return result


def _parse_source_config(raw: Any) -> dict[str, dict[str, bool | str]]:
    """
    Parse a raw source block: ``{table_name: {field: true/false/"alias"}}``.
    """
    if not isinstance(raw, dict):
        return {}
    result: dict[str, dict[str, bool | str]] = {}
    for table_name, table_cfg in raw.items():
        result[str(table_name)] = _parse_table_config(table_cfg)
    return result


