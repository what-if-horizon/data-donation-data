"""
Export configuration management (``ddd_export.yaml``).

YAML structure
--------------

.. code-block:: yaml

    # Optional: give human-readable names to task IDs.
    tasks:
      "10": YouTube Watch History
      "20": Chrome Browsing History

    # Optional: give human-readable names to assignment IDs.
    assignments:
      "1": Pilot Round
      "2": Main Study

    # ── Field settings ──────────────────────────────────────────────────

    # One section per source.
    #
    # Each key is a canonical output name.  The list under it contains all
    # source field names that should be merged into that canonical name.
    # A field listed under its own name is a simple pass-through.
    #
    # Fields under the special ``.excluded`` key are dropped from exports.
    #
    # Fields not mentioned anywhere are included as-is (same as listing
    # them under their own name).

    facebook:
      created:          # canonical output name
        - created       # source field (pass-through)
        - gemaakt       # aliased to 'created'
      .included:
        - title
        - url
      .excluded:
        - feed
        - join requests

Running ``init_export_yaml`` is always safe: it adds newly discovered
fields while leaving all existing settings untouched.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

import yaml

#: Default path for the export configuration file.
DEFAULT_YAML_PATH = Path("ddd_export.yaml")

#: Top-level YAML keys that are not source names.
_RESERVED_KEYS: frozenset[str] = frozenset({"tasks", "assignments"})

#: Special key within a source block listing excluded fields.
_EXCLUDED_KEY = ".excluded"

#: Special key within a source block listing pass-through fields.
_INCLUDED_KEY = ".included"

_YAML_HEADER = """\
# ddd_export.yaml — export configuration
# Generated by `ddd create-config`. Edit freely; re-run to pick up new fields.
#
# tasks (optional)
#   Map task IDs (strings) to human-readable names.
#   tasks:
#     "10": YouTube Watch History
#     "20": Chrome Browsing History
#
# assignments (optional)
#   Map assignment IDs (strings) to human-readable names.
#   assignments:
#     "1": Pilot Round
#     "2": Main Study
#
# Per-source field settings
#   .included  — flat list of fields to include as-is (pass-throughs)
#   .excluded  — flat list of fields to drop from exports
#   Other keys — canonical output name with a list of source fields merged into it
#                (a field under its own name in .included is a pass-through)
#
#   Fields not mentioned anywhere are included as-is (same as .included).
#
#   Example:
#     facebook:
#       created:           <- canonical group (alias/rename)
#         - created
#         - gemaakt
#       .included:
#         - title
#         - url
#       .excluded:
#         - feed
#         - join requests

"""


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _parse_source_config(raw: Any) -> tuple[dict[str, list[str]], list[str]]:
    """
    Parse a raw source block from the YAML into ``(groups, excluded)``.

    ``groups``
        ``{canonical: [field, ...]}`` — canonical output name → list of
        source fields that map to it.
    ``excluded``
        Flat list of field names to exclude.

    Handles the previous ``{field: bool|str}`` format gracefully by
    treating ``true`` as a pass-through and ``str`` as an alias target.
    """
    if not isinstance(raw, dict):
        return {}, []

    groups: dict[str, list[str]] = {}
    excluded: list[str] = []

    for key, val in raw.items():
        if key == _EXCLUDED_KEY:
            if isinstance(val, list):
                excluded = [str(f) for f in val]
            continue

        if key == _INCLUDED_KEY:
            if isinstance(val, list):
                for item in val:
                    groups[str(item)] = [str(item)]
            continue

        # New list format.
        if isinstance(val, list):
            groups[str(key)] = [str(f) for f in val]
            continue

        # Backward-compat: old bool format → pass-through or exclude.
        if isinstance(val, bool):
            if val:
                groups[str(key)] = [str(key)]
            else:
                excluded.append(str(key))
            continue

        # Backward-compat: old string alias format → alias.
        if isinstance(val, str):
            groups[str(val)] = groups.get(str(val), [])
            groups[str(val)].append(str(key))
            continue

        # Old dict format {include: bool, aliases: [...]}.
        if isinstance(val, dict):
            include = bool(val.get("include", True))
            aliases = [str(a) for a in val.get("aliases", [])]
            if include:
                groups[str(key)] = [str(key)] + aliases
            else:
                excluded.append(str(key))
                excluded.extend(aliases)

    return groups, excluded


